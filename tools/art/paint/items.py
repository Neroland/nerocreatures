def sigil(name: str, habitat: str, legend: str, crown) -> None:
    """The shared medallion: a rimmed disc on a cord loop; ``crown`` is the boss's 8x6 silhouette."""
    art = """
................
......rrrr......
.....r....r.....
....rrrrrrrr....
...rrffffffrr...
..rrffffffffrr..
..rffffffffffr..
..rffffffffffr..
..rffffffffffr..
..rffffffffffr..
..rffffffffffr..
..rrffffffffrr..
...rrffffffrr...
....rrrrrrrr....
................
................
""".split()
    rows = [list(row) for row in art]
    for y, line in enumerate(crown):
        for x, ch in enumerate(line):
            if ch != ".":
                rows[5 + y][4 + x] = ch
    ITEMS[name] = sprite(habitat, legend, ["".join(row) for row in rows])


