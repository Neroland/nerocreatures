def overlay(base, marks) -> list:
    rows = [list(row) for row in base]
    for y, line in enumerate(marks):
        for x, ch in enumerate(line):
            if ch != "." and rows[y][x] != ".":
                rows[y][x] = ch
    return ["".join(row) for row in rows]


def laid_egg(name: str, habitat: str, legend: str, marks: str) -> None:
    ITEMS[name] = sprite(habitat, legend, overlay(LAID_EGG, marks.split()))


