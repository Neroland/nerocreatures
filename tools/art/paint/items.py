SHEET_ORDER_TAIL = [name + "_spawn_egg" for name in SPAWN_EGGS]


def main(argv: list) -> int:
    check = "--check" in argv
    failed = write_images(ITEM_TEXTURES, ITEMS, check)
    present = set(n[:-4] for n in os.listdir(ITEM_TEXTURES) if n.endswith(".png"))
    for stray in sorted(present - set(ITEMS)):
        print("FAIL  textures/item/%s.png has no painter" % stray)
        failed += 1
    if "--sheet" in argv:
        order = [n for n in ITEMS if not n.endswith("_spawn_egg")] + SHEET_ORDER_TAIL
        contact_sheet(argv[argv.index("--sheet") + 1], {n: ITEMS[n] for n in order}, columns=12,
                      title="NEROCREATURES ITEMS (%d)" % len(order))
    print("items: %d textures, %s" % (len(ITEMS), "FAILED" if failed else "clean"))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
