#!/usr/bin/env python3
"""NeroCreatures sound synthesiser.

Every sound in the mod is generated here from oscillators, noise, envelopes
and filters (kit.py, standard library only). No samples, no recordings, no
third-party audio: this script is the provenance record.

  python3 -B tools/sound/synth.py            render all, encode, write manifest
  python3 -B tools/sound/synth.py --only moth  render matching events only
  python3 -B tools/sound/synth.py --check    re-synthesise and verify outputs
  python3 -B tools/sound/synth.py --check --fast   skip the re-synthesis
  python3 -B tools/sound/synth.py --table    print the review table (markdown)

Rendering needs `ffmpeg` (libvorbis) on PATH. --check does not: it
re-synthesises every sound and compares the PCM hash with the manifest, then
verifies each committed .ogg (hash, Ogg/Vorbis header, mono, 44.1 kHz) and
that the manifest still matches the event table. --fast skips the
re-synthesis; use it where a different C maths library could round a sample
differently from the machine that rendered the files.
"""
import hashlib
import json
import math
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import kit  # noqa: E402
from events import ASSET_DIR, EVENTS  # noqa: E402

MANIFEST = os.path.join(HERE, "manifest.json")
VARIANT_PITCH = (1.0, 0.93, 1.07)
MAX_SECONDS, MAX_LOOP_SECONDS = 2.5, 4.0
MAX_FILE_BYTES, MAX_TOTAL_BYTES = 40 * 1024, 3 * 1024 * 1024
QUALITY = "3"


def sound_names(ev):
    base = "%s_%s" % (ev["owner"], ev["event"])
    if ev["variants"] == 1:
        return [base]
    return ["%s_%d" % (base, i + 1) for i in range(ev["variants"])]


def render(ev, index):
    """Return (pcm bytes, seconds, peak dBFS) for one variant of an event."""
    name = sound_names(ev)[index]
    x = ev["fn"](kit.rng_for(name), VARIANT_PITCH[index])
    limit = MAX_LOOP_SECONDS if ev["loop"] else MAX_SECONDS
    cut = len(x) > kit.N(limit)
    x = kit.norm(kit.trim(x, limit))
    if ev["loop"]:
        x = kit.fade(x, 0.002, 0.002)
    else:
        x = kit.fade(x, 0.0005, 0.3 if cut else 0.03)
    peak = max(max(x), -min(x))
    return kit.to_pcm16(x), len(x) / kit.SR, 20.0 * math.log10(peak)


def encode(pcm):
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-f", "s16le", "-ar", str(kit.SR), "-ac", "1", "-i", "pipe:0",
           "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact", "-c:a", "libvorbis", "-q:a", QUALITY,
           "-ar", "44100", "-ac", "1", "-f", "ogg", "pipe:1"]
    return subprocess.run(cmd, input=pcm, stdout=subprocess.PIPE, check=True).stdout


def sha(b):
    return hashlib.sha256(b).hexdigest()


def ogg_info(data):
    """(channels, rate) from the Vorbis identification header."""
    if data[:4] != b"OggS":
        raise ValueError("not an Ogg stream")
    nseg = data[26]
    body = data[27 + nseg:]
    if body[:7] != b"\x01vorbis":
        raise ValueError("not Vorbis")
    channels = body[11]
    rate = struct.unpack("<I", body[12:16])[0]
    return channels, rate


def entry(ev, sounds):
    return {
        "id": ev["id"],
        "sound_event": "nerocreatures:" + ev["id"],
        "owner": ev["owner"],
        "owner_kind": ev["owner_kind"],
        "habitat": ev["habitat"],
        "used_for": ev["use"],
        "category": ev["category"],
        "subtitle_key": "subtitles.nerocreatures." + ev["id"],
        "subtitle": ev["subtitle"],
        "volume": ev["volume"],
        "pitch": list(ev["pitch"]),
        "range": ev["range"],
        "loop": ev["loop"],
        "sounds": sounds,
    }


def load_manifest():
    with open(MANIFEST, encoding="utf-8") as f:
        return json.load(f)


def write_manifest(entries):
    doc = {
        "_comment": "Generated by tools/sound/synth.py from tools/sound/events.py. Do not edit by hand.",
        "namespace": "nerocreatures",
        "format": {"codec": "ogg vorbis", "channels": 1, "rate": 44100, "quality": int(QUALITY), "peak_dbfs": -3.0},
        "pitch_note": "pitch is [min, max]; pick uniformly per play. range is the attenuation distance in blocks.",
        "events": entries,
    }
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=2)
        f.write("\n")


def cmd_render(only):
    old = {}
    if os.path.exists(MANIFEST):
        old = {e["id"]: e for e in load_manifest()["events"]}
    entries, total = [], 0
    for ev in EVENTS:
        if only and only not in ev["id"]:
            if ev["id"] not in old:
                sys.exit("--only needs an existing manifest entry for " + ev["id"])
            entries.append(old[ev["id"]])
            continue
        sounds = []
        for i, name in enumerate(sound_names(ev)):
            pcm, secs, peak = render(ev, i)
            ogg = encode(pcm)
            rel = "%s/%s/%s.ogg" % (ASSET_DIR, ev["folder"], name)
            path = os.path.join(ROOT, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            if not (os.path.exists(path) and open(path, "rb").read() == ogg):
                with open(path, "wb") as f:
                    f.write(ogg)
            sounds.append({"name": "nerocreatures:%s/%s" % (ev["folder"], name), "file": rel, "seconds": round(secs, 3),
                           "peak_dbfs": round(peak, 2), "bytes": len(ogg), "pcm_sha256": sha(pcm), "ogg_sha256": sha(ogg)})
            total += len(ogg)
            print("%-34s %5.2fs %6d B" % (name, secs, len(ogg)))
        entries.append(entry(ev, sounds))
    write_manifest(entries)
    files = sum(len(e["sounds"]) for e in entries)
    size = sum(s["bytes"] for e in entries for s in e["sounds"])
    print("%d events, %d files, %d bytes (%.2f MB)" % (len(entries), files, size, size / 1048576.0))


def cmd_check(fast):
    errors = []
    man = load_manifest()["events"]
    by_id = {e["id"]: e for e in man}
    ids = [ev["id"] for ev in EVENTS]
    if len(set(ids)) != len(ids):
        errors.append("duplicate event ids in events.py")
    if [e["id"] for e in man] != ids:
        errors.append("manifest events differ from events.py (re-run synth.py)")
    total, files, seen = 0, 0, set()
    for ev in EVENTS:
        m = by_id.get(ev["id"])
        if m is None:
            continue
        if not ev["subtitle"].strip():
            errors.append(ev["id"] + ": no subtitle")
        want = entry(ev, m["sounds"])
        if want != m:
            errors.append(ev["id"] + ": manifest fields are stale")
        names = sound_names(ev)
        if [s["name"].split("/")[-1] for s in m["sounds"]] != names:
            errors.append(ev["id"] + ": variant list differs")
            continue
        for i, s in enumerate(m["sounds"]):
            files += 1
            seen.add(s["file"])
            path = os.path.join(ROOT, s["file"])
            if not os.path.exists(path):
                errors.append(s["file"] + ": missing")
                continue
            data = open(path, "rb").read()
            total += len(data)
            if sha(data) != s["ogg_sha256"] or len(data) != s["bytes"]:
                errors.append(s["file"] + ": file differs from the manifest")
            try:
                ch, rate = ogg_info(data)
                if (ch, rate) != (1, 44100):
                    errors.append("%s: expected mono 44100, found %d ch %d Hz" % (s["file"], ch, rate))
            except ValueError as ex:
                errors.append("%s: %s" % (s["file"], ex))
            if len(data) > MAX_FILE_BYTES:
                errors.append("%s: %d bytes is over the per-file limit" % (s["file"], len(data)))
            if s["seconds"] > (MAX_LOOP_SECONDS if ev["loop"] else MAX_SECONDS) + 0.001:
                errors.append(s["file"] + ": too long")
            if not fast:
                pcm, _, _ = render(ev, i)
                if sha(pcm) != s["pcm_sha256"]:
                    errors.append(s["file"] + ": recipe output differs from the committed sound")
    base = os.path.join(ROOT, ASSET_DIR)
    for d, _, fs in os.walk(base):
        for fn in fs:
            rel = os.path.relpath(os.path.join(d, fn), ROOT).replace(os.sep, "/")
            if fn.endswith(".ogg") and rel not in seen:
                errors.append(rel + ": not in the manifest")
    if total > MAX_TOTAL_BYTES:
        errors.append("total %d bytes is over the %d limit" % (total, MAX_TOTAL_BYTES))
    for e in errors:
        print("FAIL " + e)
    print("sound check: %d events, %d files, %.2f MB, %s%s" % (
        len(man), files, total / 1048576.0, "resynthesised, " if not fast else "", "%d problem(s)" % len(errors) if errors else "ok"))
    return 1 if errors else 0


def cmd_table():
    print("| event | file | seconds | peak dBFS | bytes | category | subtitle |")
    print("|---|---|---|---|---|---|---|")
    for e in load_manifest()["events"]:
        for s in e["sounds"]:
            print("| %s | %s | %.2f | %.1f | %d | %s | %s |" % (e["id"], s["name"].split(":")[1], s["seconds"], s["peak_dbfs"],
                                                               s["bytes"], e["category"], e["subtitle"]))


def main(argv):
    if "--check" in argv:
        return cmd_check("--fast" in argv)
    if "--table" in argv:
        cmd_table()
        return 0
    only = argv[argv.index("--only") + 1] if "--only" in argv else None
    cmd_render(only)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
